import { realpathSync } from 'node:fs';
import { sep } from 'node:path';
import { Project, ts } from 'ts-morph';
import { loadDiscoveryTsconfig, resolveTsconfigPath } from './contracts-fast.js';
import type { ContractSource, RouteDescriptor } from './types.js';

/**
 * `types: 'standalone'` — resolve every route's request/response types with the
 * TypeScript checker and print them as self-contained type text.
 *
 * The default (`'reference'`) emits `Awaited<ReturnType<import('<controller>')…>>`
 * and `import type` statements pointing at server source, so whatever type-checks
 * the generated client also type-checks the server (its decorators, its Node
 * types, its whole import graph). That is fine when client and server share one
 * tsconfig and not fine when the client lives in another package — a Vite SPA, a
 * mobile app, a shared `packages/client` — which then drags in the entire API.
 *
 * Standalone mode asks the checker for what each handler actually returns
 * (inferred return types included) and what its `@Body()`/`@Query()` accept, and
 * prints that. Named types declared in the app (interfaces, classes, type aliases,
 * enums) are hoisted into `types.ts` and referenced by name; everything else —
 * anonymous object types, library types such as Drizzle's inferred rows — is
 * inlined structurally. The generated files then import nothing from the server.
 *
 * A validation pipe's schema is preferred over the parameter annotation when it
 * is a Standard Schema (zod ≥ 3.24, valibot, arktype): `@Body(new ZodPipe(s))`
 * types the body as the schema's INPUT (`.default()` fields optional), which is
 * what a client sends, rather than the parsed output the handler receives.
 */

/** Where hoisted declarations are referenced from inside api.ts. */
export const STANDALONE_TYPES_NAMESPACE = '$types';

/** Placeholder the printer writes before a hoisted name; resolved per output file. */
const REF = '\u0000ref:';

export interface StandaloneTypesOptions {
  /** Project root (for input tracking). */
  cwd: string;
  /** tsconfig of the server app (`app.tsconfig`, else `<cwd>/tsconfig.json`). */
  tsconfig?: string | undefined;
}

export interface StandaloneTypesResult {
  /** The routes, their body/query/response replaced by self-contained type text. */
  routes: RouteDescriptor[];
  /** `types.ts` source (hoisted named types), or null when nothing was hoisted. */
  typesModule: string | null;
  /** Local (non-node_modules) source files the program read — generate inputs. */
  inputs: string[];
}

export function resolveStandaloneTypes(
  routes: RouteDescriptor[],
  opts: StandaloneTypesOptions,
): StandaloneTypesResult {
  const tsconfigPath = resolveTsconfigPath(opts.cwd, opts.tsconfig);
  const loaded = loadDiscoveryTsconfig(tsconfigPath);
  const project = new Project({
    compilerOptions: { ...(loaded.options ?? {}), noEmit: true, strict: true },
    skipAddingFilesFromTsConfig: true,
  });

  const files = new Set<string>();
  for (const r of routes) if (r.controllerRef) files.add(r.controllerRef.filePath);
  for (const f of files) project.addSourceFileAtPathIfExists(f);

  const program = project.getProgram().compilerObject;
  const checker = program.getTypeChecker();
  const printer = new TypePrinter(checker, program);

  const out = routes.map((route) => {
    const cs = route.contract?.contractSource;
    const ref = route.controllerRef;
    if (!cs || !ref) return route;
    const handler = findHandler(program, checker, ref.filePath, ref.className, ref.methodName);
    if (!handler) return route;
    const next = resolveRoute(printer, checker, handler, cs);
    return next ? { ...route, contract: { ...route.contract, contractSource: next } } : route;
  });

  const inputs = program
    .getSourceFiles()
    .filter((sf) => !program.isSourceFileDefaultLibrary(sf) && !isExternal(sf.fileName))
    .map((sf) => sf.fileName)
    .sort();

  const declarations = printer.declarations();
  return {
    routes: out.map((r) => bindRefs(r, `${STANDALONE_TYPES_NAMESPACE}.`)),
    typesModule:
      declarations.length > 0
        ? [
            '// Generated by @dudousxd/nestjs-codegen. Do not edit.',
            '// Types the API routes use, resolved from the server source (`types: "standalone"`).',
            '',
            ...declarations.map((d) => d.split(REF).join('')),
            '',
          ].join('\n')
        : null,
    inputs,
  };
}

// ---------------------------------------------------------------------------
// Route resolution
// ---------------------------------------------------------------------------

interface Handler {
  signature: ts.Signature;
  /** The handler's declaration, for reading parameter decorators. */
  declaration: ts.SignatureDeclaration;
}

function findHandler(
  program: ts.Program,
  checker: ts.TypeChecker,
  filePath: string,
  className: string,
  methodName: string,
): Handler | null {
  const sf = program.getSourceFile(filePath);
  if (!sf) return null;
  const cls = sf.statements.find(
    (s): s is ts.ClassDeclaration => ts.isClassDeclaration(s) && s.name?.text === className,
  );
  if (!cls?.name) return null;
  const classSymbol = checker.getSymbolAtLocation(cls.name);
  if (!classSymbol) return null;
  // The INSTANCE type, so an inherited (factory-produced) handler resolves with
  // the derived class's type arguments already substituted.
  const instance = checker.getDeclaredTypeOfSymbol(classSymbol);
  const prop = checker.getPropertyOfType(instance, methodName);
  if (!prop) return null;
  const signature = checker.getTypeOfSymbolAtLocation(prop, cls).getCallSignatures()[0];
  const declaration = signature?.getDeclaration();
  if (!signature || !declaration) return null;
  return { signature, declaration };
}

function resolveRoute(
  printer: TypePrinter,
  checker: ts.TypeChecker,
  handler: Handler,
  cs: ContractSource,
): ContractSource | null {
  const next: ContractSource = { ...cs, standalone: true };

  // Streams keep the discovered element type and binary routes are `RawResponse<Blob>`
  // regardless; every other response is what the handler resolves to.
  if (!cs.stream && !cs.binaryResponse) {
    const returned = handler.signature.getReturnType();
    const awaited = checker.getAwaitedType(returned) ?? returned;
    next.response = printer.print(awaited);
    next.responseRef = null;
  }

  // Keep a body/query the static pass rendered from a filter (`@ApplyFilter`) —
  // the filter extension owns that shape.
  const body = requestType(printer, checker, handler, 'Body');
  if (body !== undefined && !(cs.filterSource === 'body' && cs.filterFields?.length)) {
    next.body = body;
    next.bodyRef = null;
  }
  const query = requestType(printer, checker, handler, 'Query');
  if (query !== undefined && !(cs.filterSource === 'query' && cs.filterFields?.length)) {
    next.query = query;
    next.queryRef = null;
  }
  return next;
}

/**
 * The type a client sends for `@Body()` / `@Query()`: the whole-object parameter
 * (`@Body()`, `@Body(pipe)`) or, failing that, the named-property parameters
 * (`@Body('title')`) as one object. `undefined` when the handler has none.
 */
function requestType(
  printer: TypePrinter,
  checker: ts.TypeChecker,
  handler: Handler,
  decoratorName: 'Body' | 'Query',
): string | undefined {
  const named: string[] = [];
  const params = handler.declaration.parameters;
  for (const [index, param] of params.entries()) {
    const decorator = findDecorator(param, decoratorName);
    if (!decorator) continue;
    const symbol = handler.signature.getParameters()[index];
    const declared = symbol ? checker.getTypeOfSymbol(symbol) : checker.getTypeAtLocation(param);
    const args = ts.isCallExpression(decorator.expression) ? decorator.expression.arguments : [];
    const first = args[0];
    const property = first && ts.isStringLiteralLike(first) ? first.text : null;
    const schemaInput = pipeSchemaInput(checker, property === null ? args : args.slice(1));
    const type = schemaInput ?? declared;
    if (property === null) return printer.print(type);
    const optional = !!param.questionToken || !!param.initializer;
    named.push(
      `${propertyKey(property)}${optional ? '?' : ''}: ${printer.print(optional ? checker.getNonNullableType(type) : type)}`,
    );
  }
  return named.length > 0 ? `{ ${named.join('; ')} }` : undefined;
}

function findDecorator(node: ts.Node, name: string): ts.Decorator | undefined {
  const decorators = ts.canHaveDecorators(node) ? ts.getDecorators(node) : undefined;
  return decorators?.find((d) => {
    const callee = ts.isCallExpression(d.expression) ? d.expression.expression : d.expression;
    return ts.isIdentifier(callee) && callee.text === name;
  });
}

/**
 * The INPUT type of the first Standard Schema handed to a pipe in these decorator
 * arguments (`new ZodPipe(schema)`, `new ValibotPipe(schema)`), or null.
 */
function pipeSchemaInput(checker: ts.TypeChecker, args: readonly ts.Expression[]): ts.Type | null {
  for (const arg of args) {
    if (!ts.isNewExpression(arg) && !ts.isCallExpression(arg)) continue;
    for (const candidate of arg.arguments ?? []) {
      const input = standardSchemaInput(checker, checker.getTypeAtLocation(candidate));
      if (input) return input;
    }
  }
  return null;
}

/** `T['~standard']['types']['input']` of a Standard Schema type, or null. */
function standardSchemaInput(checker: ts.TypeChecker, schema: ts.Type): ts.Type | null {
  const standard = checker.getPropertyOfType(schema, '~standard');
  if (!standard) return null;
  const types = checker.getPropertyOfType(checker.getTypeOfSymbol(standard), 'types');
  if (!types) return null;
  const input = checker.getPropertyOfType(
    checker.getNonNullableType(checker.getTypeOfSymbol(types)),
    'input',
  );
  return input ? checker.getTypeOfSymbol(input) : null;
}

/** Resolve the printer's placeholders in a route's type text to `prefix` + name. */
function bindRefs(route: RouteDescriptor, prefix: string): RouteDescriptor {
  const cs = route.contract?.contractSource;
  if (!cs?.standalone) return route;
  const bind = <T extends string | null | undefined>(text: T): T =>
    (typeof text === 'string' ? text.split(REF).join(prefix) : text) as T;
  return {
    ...route,
    contract: {
      ...route.contract,
      contractSource: {
        ...cs,
        response: bind(cs.response),
        body: bind(cs.body),
        query: bind(cs.query),
      },
    },
  };
}

